    # стреляли почти периодически, разброс ответов мал и R-STDP не учился (замер: README).
    bg_rate = 200.0                  # Гц пуассоновских внешних AMPA-событий на нейрон; допущение
    bg_w = 0.016                     # мСм/см2 на событие; допущение
    bg_w_fs_mult = 0.9               # множитель фона для FS; подобран (допущение)

    # ---------------- гелевая среда (gel.py)
    temperature = 36.0               # °C
    temp_ref = 36.0                  # кинетика Pospischil 2008 дана при 36 °C
    q10_gate = 3.0                   # Q10 скоростей затворов: ~3 (Hodgkin & Huxley 1952; Hille 2001)
    q10_cond = 1.3                   # Q10 максимальных проводимостей ~1.2–1.5 (Hille 2001); допущение в выборе 1.3
    q10_syn = 2.0                    # Q10 скорости спада синаптических токов; допущение (порядок 2–3)
    mg_mM = 1.0                      # [Mg2+]o, мМ (ТЗ); блок NMDA по Jahr & Stevens 1990
    viscosity = 1.0                  # отн. вязкость геля (1.0 = опорная)
    visc_exponent = 0.5              # conn_radius = ref * (eta_ref/eta)^0.5; допущение (качественно: рост
                                     # нейритов медленнее в более вязкой/жёсткой матрице, Balgude et al. 2001)
    # внеклеточный K+ (диффузия на сетке вокселей)
    k_enabled = True
    k_rest = 3.0                     # мМ, [K+]o покоя; допущение (ИСЖ 2.5–3.5 мМ)
    k_voxel = 50.0                   # мкм, шаг сетки
    k_D = 1.96                       # мкм2/мс = 1.96e-5 см2/с, K+ в воде (CRC Handbook)
    k_tortuosity = 1.6               # Nicholson & Syková 1998 (мозг); для геля меньше — допущение
    k_alpha = 0.2                    # доля внеклеточного объёма (Nicholson & Syková 1998)
    k_per_spike_fmol = 0.36          # фмоль K+ на спайк (≈3 x C*dV*A/F для RS); допущение
